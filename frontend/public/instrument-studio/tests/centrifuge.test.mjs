import assert from 'node:assert/strict';
import '../instruments/centrifuge-state.js';
const State = globalThis.LabCentrifugeState;
let checks = 0;
function check(value, name) { checks++; assert.ok(value, name); }
const s = new State();
check(!s.start(), 'open lid blocks start');
check(s.toggleSlot(0) && !s.balanced, 'single tube is unmatched');
check(s.toggleSlot(12) && s.balanced, 'opposite identical tube balances');
check(!s.toggleRotor(), 'loaded rotor cannot be removed');
check(s.toggleCover(), 'rotor cover installs');
check(!s.toggleSlot(1), 'cover blocks loading');
check(s.toggleLid(), 'lid closes');
check(s.start(), 'prepared instrument starts');
check(!s.toggleLid(), 'running lid interlock');
check(!s.toggleCover(), 'running cover interlock');
check(!s.toggleRotor(), 'running rotor interlock');
for (let i=0;i<30;i++) s.tick(.1);
check(s.phase === 'running' && s.speed === 1, 'acceleration completes');
check(s.stop() && s.phase === 'decelerating', 'stop initiates deceleration');
check(!s.toggleLid(), 'lid remains locked during deceleration');
for (let i=0;i<30;i++) s.tick(.1);
check(s.phase === 'complete' && s.speed === 0, 'rotor stops before unlock');
check(s.toggleLid() && s.toggleCover() && s.unload(), 'completed run unloads');
check(s.toggleRotor() && !s.rotorInstalled, 'empty rotor removes');
check(!s.toggleSlot(0), 'no loading absent rotor');
check(!s.toggleCover(), 'no cover on absent rotor');
check(s.toggleRotor() && s.loadPair(), 'rotor reinstalls and pair loads');
check(!s.toggleSlot(24) && !s.toggleSlot(-1), 'invalid indexes rejected');
s.toggleSlot(1);s.toggleCover();s.toggleLid();
check(!s.start(), 'unmatched load blocks start');
s.toggleLid();s.toggleCover();s.toggleSlot(1);s.toggleCover();s.toggleLid();
check(s.start(), 'balanced load restarts');
for(let i=0;i<220;i++)s.tick(.1);
check(s.phase==='complete'&&s.speed===0, 'full timed cycle completes');
const snap=s.snapshot();snap.slots[0]=null;
check(s.slots[0]!==null,'exported snapshot cannot mutate state');
console.log(`${checks} centrifuge assertions passed`);
export {checks};
